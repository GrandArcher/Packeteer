package main

import (
	"fmt"
	"net/netip"
	"strconv"
	"strings"
	"time"
)

// Ports on the host network. The container and the harness share it.
type ports struct {
	BGP  int // the harness's router; Packeteer connects to it
	Flow int // Packeteer's IPFIX collector
	HTTP int // Packeteer's ops API
}

// probeInterval is probe.interval in the generated config.
const probeInterval = 30 * time.Second

// v4Targets is how many IPv4 entries an inject run adds as static targets.
// Churn never touches IPv4, so these are what the withdraw-latency check
// picks from.
const v4Targets = 128

// packeteerConfig is the config the stock image runs with: a learn-only
// iBGP session to each of the harness's routers, the flow source, many
// static targets, and the fixed prober (no packets leave the host).
// transit-b is faster, so roughly half the measured prefixes have a
// recommendation. Observe announces none of them; inject announces up to
// p.Inject, inside an allowlist of the documentation blocks the table uses.
func packeteerConfig(p Profile, pt ports, dataDir string) string {
	tbl := newTable(p.Prefixes)
	mode, maxImp, hold, allow, lp := "observe", 50, "15m", "  prefixes: []\n", ""
	if p.Inject > 0 {
		// A short hold time, so a prefix the withdraw check took back can
		// be injected again within the run.
		mode, maxImp, hold, lp = "inject", p.Inject, "1m", "local_pref: 250\n"
		allow = "  prefixes:\n"
		for _, d := range append(append([]netip.Prefix{}, docV4...), docV6) {
			allow += fmt.Sprintf("    - \"%s\"\n", d)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by lab/soak for the load and soak test (#51). Lab only:
# documentation prefixes and ASNs, no packets leave the host.
mode: %s
asn: %d
router_id: 192.0.2.10
packeteer_community: "64512:666"
%smax_improvements: %d
hold_time: %s
thresholds:
  min_loss_delta_pct: 1.0
  min_rtt_delta_ms: 15
providers:
%sallowlist:
%sbgp:
  neighbors:
`, mode, labASN, lp, maxImp, hold, providerLines(p), allow)
	for k := range p.sessions() {
		desc := "soak-router"
		if k > 0 {
			desc = fmt.Sprintf("soak-router-%d", k)
		}
		fmt.Fprintf(&b, "    - address: %s\n      port: %d\n      local_address: %s\n      description: %s\n", routerAddrs[k], pt.BGP, peerAddr, desc)
	}
	if p.Inject > 0 {
		b.WriteString("announcer:\n  type: gobgp\n")
	}
	fmt.Fprintf(&b, `probe:
  interval: %s
  timeout: 1s
  packets: 4
  workers: 8
  rate_limit_pps: %d
`, probeInterval, rateLimit(p))
	targets := staticTargets(p, tbl)
	if p.Simulate {
		b.WriteString(simProber())
		b.WriteString(simTelemetry())
	} else {
		b.WriteString("probers:\n  - type: fixed\n    config:\n      paths:\n")
		for _, i := range targets[:p.OutageTargets] {
			prov := "transit-a"
			if i >= v4Count {
				prov = "transit-a6"
			}
			fmt.Fprintf(&b, "        - {provider: %s, target: \"%s\", rtt_ms: 40, loss_pct: 100}\n", prov, tbl.host(i))
		}
		b.WriteString(`        - {provider: transit-a, rtt_ms: 40}
        - {provider: transit-b, rtt_ms: 10}
        - {provider: transit-a6, rtt_ms: 40}
        - {provider: transit-b6, rtt_ms: 10}
`)
	}
	fmt.Fprintf(&b, `log:
  level: info
  format: text
http:
  listen: "127.0.0.1:%d"
auth:
  enabled: false
storage:
  type: sqlite
  config:
    path: %s/packeteer.db
sources:
  - type: flow
    config:
      listen: "127.0.0.1:%d"
      window: 5m
      top_n: %d
`, pt.HTTP, strings.TrimRight(dataDir, "/"), pt.Flow, max(1, p.FlowTopN))
	if len(targets) > 0 {
		b.WriteString("  - type: static\n    config:\n      targets:\n")
		for _, i := range targets {
			fmt.Fprintf(&b, "        - {prefix: \"%s\", host: \"%s\"}\n", tbl.prefix(i), tbl.host(i))
		}
	}
	if p.VIPTargets > 0 {
		// The first documentation ASN is in about a fifth of the AS paths,
		// so the expansion reaches max_targets.
		asns := []uint32{docASNs[0]}
		if p.Simulate {
			asns = p.vipASNs
		}
		fmt.Fprintf(&b, "  - type: vip\n    config:\n      interval: 10s\n      asns: %s\n      max_targets: %d\n", intList(asns), p.VIPTargets)
	}
	if p.OutageTargets > 0 {
		b.WriteString("  - type: outage\n    config:\n      min_prefixes: 3\n      interval: 5s\n")
	}
	return b.String()
}

// staticTargets is the entries of the static source: p.StaticTargets
// spread over the table, then on inject runs v4Targets spread over the
// IPv4 entries.
func staticTargets(p Profile, tbl table) []int {
	var out []int
	seen := map[int]bool{}
	add := func(i int) {
		if !seen[i] {
			seen[i] = true
			out = append(out, i)
		}
	}
	for k := range p.StaticTargets {
		add(k * (p.Prefixes / p.StaticTargets))
	}
	if p.Inject > 0 {
		for k := range v4Targets {
			add(k * min(v4Count, tbl.n) / v4Targets)
		}
	}
	return out
}

// rateLimit is the generated probe.rate_limit_pps. The pr and soak
// profiles leave it unset and keep 100000 so the fixed prober is not
// what bounds the run. The rate profile sets 100, the operator default.
func rateLimit(p Profile) int {
	if p.RateLimitPPS > 0 {
		return p.RateLimitPPS
	}
	return 100000
}

// providerLines is the providers block. The synthetic and plain real
// profiles have two providers per family. A simulated real-table run has
// one per view, as lab providers with a type, an ASN, and a cost (#103).
func providerLines(p Profile) string {
	if !p.Simulate {
		return fmt.Sprintf(`  - {name: transit-a, source_ip: 192.0.2.11, next_hop: %s}
  - {name: transit-b, source_ip: 192.0.2.12, next_hop: %s}
  - {name: transit-a6, source_ip: "2001:db8:ffff::11", next_hop: "%s"}
  - {name: transit-b6, source_ip: "2001:db8:ffff::12", next_hop: "%s"}
`, nextHopsV4[0], nextHopsV4[1], nextHopsV6[0], nextHopsV6[1])
	}
	var b strings.Builder
	for k, r := range simRoutes[:p.sessions()] {
		fmt.Fprintf(&b, "  - {name: %s, source_ip: 192.0.2.%d, next_hop: %s, type: %s, asn: %d, cost: %v}\n",
			r.name, 11+k, nextHopsV4[k], r.kind, r.asn, r.cost)
		fmt.Fprintf(&b, "  - {name: %s6, source_ip: \"2001:db8:ffff::%x\", next_hop: \"%s\", type: %s, asn: %d, cost: %v}\n",
			r.name, 0x11+k, nextHopsV6[k], r.kind, r.asn, r.cost)
	}
	return b.String()
}

func intList(a []uint32) string {
	s := make([]string, len(a))
	for i, n := range a {
		s[i] = strconv.FormatUint(uint64(n), 10)
	}
	return "[" + strings.Join(s, ", ") + "]"
}
